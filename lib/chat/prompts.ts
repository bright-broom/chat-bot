// システムプロンプトの組み立て（純粋関数のみ。環境変数や現在時刻には依存しない）
import { BLOCKED_TOPIC_RULE } from "./blocked";
import type { Mode } from "./types";

export type PromptContext = {
  /** Web 検索が有効か（OpenRouter 利用時のみ true） */
  webSearch: boolean;
  /** 検索・出典に使ってよいドメイン（例: go.jp, lg.jp） */
  allowedDomains: readonly string[];
  /** 「今日」の表記（日本時間）。例: 2026年11月28日(土) */
  today: string;
};

/** 日本時間の今日の日付を、プロンプト用の表記で返す */
export function todayJst(now: Date = new Date()): string {
  return now.toLocaleDateString("ja-JP", {
    timeZone: "Asia/Tokyo",
    year: "numeric",
    month: "long",
    day: "numeric",
    weekday: "short",
  });
}

