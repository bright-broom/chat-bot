// 「やさしい日本語」モード: 高齢の方や日本語に不慣れな方にも読みやすい表現で答える
const EASY_JAPANESE_PROMPT =
  "【やさしい日本語モード】日本語で答えるときは: 1 文は 30 字以内で 1 つのことだけ。難しい言葉・漢語・カタカナ語はふだんの言葉に言いかえる。言いかえられない用語にはかっこでやさしい説明を付ける（例: 住民票（住んでいる場所を証明する書類））。二重否定・あいまいな言い方・過剰な敬語は避け、「です・ます」で書く。日付・金額・電話番号は省略せずに書く。";

/** モード・表示設定・利用できる機能から、モデルに渡すシステムプロンプトを組み立てる（純粋関数） */
export function systemPrompt(mode: Mode, easyJapanese: boolean, ctx: PromptContext): string {
  return [
    ...(mode === "support" ? supportPrompt(ctx) : chatPrompt(ctx)),
    BLOCKED_TOPIC_RULE,
    easyJapanese ? EASY_JAPANESE_PROMPT : "",
  ]
    .filter(Boolean)
    .join("\n");
}

